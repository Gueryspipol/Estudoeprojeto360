# FUNÇÃO PARA PREENCHER TABELAS
# ============================================================

def preencher_slide_analise_15(
    slide,
    registros,
    indice_inicial
):
    """
    Preenche os blocos financeiros encontrados
    nas tabelas do slide.

    Cada bloco possui:
    Produto
    Número de Vidas
    Custo Médio
    Total
    """

    tabelas = localizar_tabelas_slide_15(
        slide
    )

    produto_atual = indice_inicial

    blocos_preenchidos = 0

    celulas_atualizadas = 0

    tabelas_processadas = 0


    for tabela in tabelas:

        ocorrencias_produto = (
            localizar_linha_rotulo_15(
                tabela,
                [
                    "Produto",
                ]
            )
        )

        if not ocorrencias_produto:
            continue

        tabelas_processadas += 1


        for ocorrencia in ocorrencias_produto:

            if produto_atual >= len(
                registros
            ):
                break

            linha_produto = ocorrencia[
                "linha"
            ]

            coluna_rotulo = ocorrencia[
                "coluna"
            ]

            registro = registros[
                produto_atual
            ]

            linhas_alvo = {
                "produto": linha_produto,
                "vidas": None,
                "custo": None,
                "total": None,
            }


            # Procurar os demais rótulos abaixo
            # ou próximos do Produto.
            for deslocamento in range(
                1,
                5
            ):

                linha_teste = (
                    linha_produto
                    + deslocamento
                )

                if linha_teste >= len(
                    tabela.rows
                ):
                    break

                texto_rotulo = (
                    limpar_texto_15(
                        tabela.cell(
                            linha_teste,
                            coluna_rotulo
                        ).text
                    ).upper()
                )

                if (
                    "NÚMERO DE VIDAS"
                    in texto_rotulo
                    or "NUMERO DE VIDAS"
                    in texto_rotulo
                    or texto_rotulo
                    == "VIDAS"
                ):
                    linhas_alvo[
                        "vidas"
                    ] = linha_teste

                elif (
                    "CUSTO MÉDIO"
                    in texto_rotulo
                    or "CUSTO MEDIO"
                    in texto_rotulo
                ):
                    linhas_alvo[
                        "custo"
                    ] = linha_teste

                elif texto_rotulo == "TOTAL":
                    linhas_alvo[
                        "total"
                    ] = linha_teste


            quantidade_colunas_dados = (
                len(tabela.columns)
                - coluna_rotulo
                - 1
            )

            quantidade_opcoes = min(
                quantidade_colunas_dados,
                len(registro["opcoes"])
            )


            for indice_opcao in range(
                quantidade_opcoes
            ):

                coluna_destino = (
                    coluna_rotulo
                    + 1
                    + indice_opcao
                )

                opcao = registro[
                    "opcoes"
                ][
                    indice_opcao
                ]


                definir_texto_celula_15(
                    tabela.cell(
                        linhas_alvo["produto"],
                        coluna_destino
                    ),
                    opcao["produto"]
                    if (
                        opcao["produto"]
                        and not eh_placeholder_15(
                            opcao["produto"]
                        )
                    )
                    else "-"
                )

                celulas_atualizadas += 1


                if linhas_alvo[
                    "vidas"
                ] is not None:

                    definir_texto_celula_15(
                        tabela.cell(
                            linhas_alvo["vidas"],
                            coluna_destino
                        ),
                        formatar_inteiro_15(
                            opcao["vidas"]
                        )
                    )

                    celulas_atualizadas += 1


                if linhas_alvo[
                    "custo"
                ] is not None:

                    definir_texto_celula_15(
                        tabela.cell(
                            linhas_alvo["custo"],
                            coluna_destino
                        ),
                        formatar_numero_15(
                            opcao["custo"]
                        )
                    )

                    celulas_atualizadas += 1


                if linhas_alvo[
                    "total"
                ] is not None:

                    definir_texto_celula_15(
                        tabela.cell(
                            linhas_alvo["total"],
                            coluna_destino
                        ),
                        formatar_numero_15(
                            opcao["total"]
                        )
                    )

                    celulas_atualizadas += 1


            produto_atual += 1

            blocos_preenchidos += 1


    return {
        "tabelas_encontradas": len(tabelas),
        "tabelas_processadas": tabelas_processadas,
        "blocos_preenchidos": blocos_preenchidos,
        "celulas_atualizadas": celulas_atualizadas,
        "proximo_produto": produto_atual,
    }


