# LOCALIZAR ABA BASE PELO CONTEÚDO
# ============================================================

def localizar_aba_base_7(wb):
    """
    Localiza uma aba visível com estrutura de cadastro de vidas.

    Não depende obrigatoriamente do nome 'Base'.
    """

    melhor_aba = None
    melhor_score = 0

    indicadores = {
        "NOME",
        "SEXO",
        "PLANO",
        "FAIXA ETARIA",
        "ELEGIBILIDADE",
        "IDADE",
        "VALOR",
    }

    for ws in wb.worksheets:

        if ws.sheet_state != "visible":
            continue

        score = 0

        limite_linhas = min(
            ws.max_row,
            30
        )

        limite_colunas = min(
            ws.max_column,
            50
        )

        encontrados = set()

        for linha in range(
            1,
            limite_linhas + 1
        ):
            for coluna in range(
                1,
                limite_colunas + 1
            ):
                texto = normalizar_7(
                    ws.cell(
                        linha,
                        coluna
                    ).value
                )

                if texto in indicadores:
                    encontrados.add(texto)

        score = len(encontrados)

        if score > melhor_score:
            melhor_score = score
            melhor_aba = ws

    if melhor_aba is None or melhor_score < 3:
        raise ValueError(
            "Nenhuma aba visível com estrutura de Base "
            "foi identificada."
        )

    return melhor_aba, melhor_score


