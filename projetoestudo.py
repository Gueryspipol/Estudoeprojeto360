def texto_limpo(valor):
    if valor is None:
        return ""

    return " ".join(
        str(valor).replace("\n", " ").split()
    ).strip()


def candidato_valido_operadora(valor):
    """
    Valida o texto encontrado ao lado de OPERADORA.

    Não existe lista fixa de nomes de operadoras.
    A função descarta apenas cabeçalhos e textos técnicos.
    """

    texto = texto_limpo(valor)

    if not texto:
        return False

    texto_maiusculo = texto.upper()

    textos_tecnicos = [
        "REAJUSTE",
        "FATURA ATUAL",
        "FATURA REAJUSTADA",
        "PLANO",
        "FAIXA ETÁRIA",
        "FAIXA ETARIA",
        "VIDAS",
        "PER CAPITA",
        "TOTAL",
        "COTAÇÃO",
        "COTACAO",
        "DESCONTO",
        "DIFERENÇA",
        "DIFERENCA",
    ]

    for termo in textos_tecnicos:
        if termo in texto_maiusculo:
            return False

    return True


def localizar_elementos_proximos(
    ws,
    linha_inicial,
    coluna_inicial,
    altura=22,
    largura=12
):
    """
    Verifica quais indicadores estruturais existem
    próximo de um ponto identificado como OPERADORA.
    """

    elementos = set()

    linha_final = min(
        ws.max_row,
        linha_inicial + altura
    )

    coluna_final = min(
        ws.max_column,
        coluna_inicial + largura
    )

    indicadores = {
        "PLANO",
        "FAIXA ETÁRIA",
        "FAIXA ETARIA",
        "VIDAS",
        "PER CAPITA",
        "CUSTO MÉDIO",
        "CUSTO MEDIO",
        "TOTAL / FATURA",
    }

    for linha in range(
        linha_inicial,
        linha_final + 1
    ):
        for coluna in range(
            coluna_inicial,
            coluna_final + 1
        ):
            valor = texto_limpo(
                ws.cell(linha, coluna).value
            ).upper()

            if valor in indicadores:
                elementos.add(valor)

    return elementos


