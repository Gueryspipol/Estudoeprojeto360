def identificar_sexo_7(valor):
    texto = normalizar_7(valor)

    if texto in {
        "F",
        "FEMININO",
    }:
        return "Feminino"

    if texto in {
        "M",
        "MASCULINO",
    }:
        return "Masculino"

    return None


def identificar_vinculo_7(valor):
    texto = normalizar_7(valor)

    if texto in {
        "T",
        "TITULAR",
        "FUNCIONARIO",
        "FUNCIONARIA",
        "COLABORADOR",
        "COLABORADORA",
    }:
        return "Funcionário"

    if texto in {
        "D",
        "DEPENDENTE",
    }:
        return "Dependente"

    if "TITULAR" in texto:
        return "Funcionário"

    if "DEPEND" in texto:
        return "Dependente"

    return None


