def localizar_blocos_planos_8b(
    ws,
    linha_inicial,
    linha_final,
    quantidade_maxima=5
):
    """
    Procura blocos que possuem:

    nome do player
    seguido de até dez linhas de produtos.

    Prioriza as posições já formatadas do modelo.
    """

    blocos = []

    for linha in range(
        linha_inicial,
        linha_final + 1
    ):

        valor = limpar_texto_8b(
            ws.cell(
                linha,
                1
            ).value
        )

        valor_b = limpar_texto_8b(
            ws.cell(
                linha,
                2
            ).value
        )

        candidato = (
            valor_b
            if valor_b
            else valor
        )

        if not candidato:
            continue

        texto = normalizar_8b(
            candidato
        )

        if texto in {
            "PLAYERS",
            "PLAYERS COLAGEM",
            "CUSTO MEDIO",
            "CUSTO MEDIO CC",
            "CUSTO MEDIO SC",
        }:
            continue

        produtos_abaixo = 0

        for deslocamento in range(
            1,
            11
        ):
            linha_teste = linha + deslocamento

            if linha_teste > linha_final:
                break

            possui_valor = False

            for coluna in range(
                1,
                min(
                    ws.max_column,
                    8
                ) + 1
            ):
                if limpar_texto_8b(
                    ws.cell(
                        linha_teste,
                        coluna
                    ).value
                ):
                    possui_valor = True
                    break

            if possui_valor:
                produtos_abaixo += 1

        if produtos_abaixo >= 5:

            blocos.append({
                "linha_nome": linha,
                "coluna_nome": (
                    2
                    if valor_b
                    else 1
                ),
            })

            if len(blocos) >= quantidade_maxima:
                break

    return blocos


