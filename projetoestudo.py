def limpar_texto_8b(valor):
    if valor is None:
        return ""

    return " ".join(
        str(valor).replace("\n", " ").split()
    ).strip()


def normalizar_8b(valor):
    texto = limpar_texto_8b(valor)

    texto = unicodedata.normalize(
        "NFKD",
        texto
    )

    texto = "".join(
        caractere
        for caractere in texto
        if not unicodedata.combining(caractere)
    )

    texto = texto.upper()

    texto = re.sub(
        r"[^A-Z0-9]+",
        " ",
        texto
    )

    return " ".join(
        texto.split()
    )


def definir_valor_8b(
    ws,
    linha,
    coluna,
    valor
):
    """
    Escreve somente em células normais.

    Se a posição fizer parte de uma célula mesclada,
    localiza a célula principal do intervalo.
    """

    celula = ws.cell(
        linha,
        coluna
    )

    if not isinstance(
        celula,
        MergedCell
    ):
        celula.value = valor
        return

    for intervalo in ws.merged_cells.ranges:

        if celula.coordinate in intervalo:

            ws.cell(
                intervalo.min_row,
                intervalo.min_col
            ).value = valor

            return


def localizar_celulas_8b(
    ws,
    texto_procurado
):
    procurado = normalizar_8b(
        texto_procurado
    )

    encontrados = []

    for linha in ws.iter_rows():

        for celula in linha:

            if isinstance(
                celula,
                MergedCell
            ):
                continue

            texto = normalizar_8b(
                celula.value
            )

            if texto == procurado:

                encontrados.append({
                    "linha": celula.row,
                    "coluna": celula.column,
                    "coordenada": celula.coordinate,
                })

    return encontrados


def localizar_primeira_celula_8b(
    ws,
    textos
):
    for texto in textos:

        resultados = localizar_celulas_8b(
            ws,
            texto
        )

        if resultados:
            return resultados[0]

    return None


def copiar_estilo_8b(
    origem,
    destino
):
    """
    Copia apenas o estilo visual da célula.
    """

    if origem.has_style:
        destino._style = copy(
            origem._style
        )

    if origem.number_format:
        destino.number_format = (
            origem.number_format
        )

    if origem.alignment:
        destino.alignment = copy(
            origem.alignment
        )

    if origem.font:
        destino.font = copy(
            origem.font
        )

    if origem.fill:
        destino.fill = copy(
            origem.fill
        )

    if origem.border:
        destino.border = copy(
            origem.border
        )


def limpar_valores_area_8b(
    ws,
    linha_inicial,
    linha_final,
    coluna_inicial,
    coluna_final
):
    """
    Limpa valores, mas preserva toda a formatação.
    """

    for linha in range(
        linha_inicial,
        linha_final + 1
    ):
        for coluna in range(
            coluna_inicial,
            coluna_final + 1
        ):

            celula = ws.cell(
                linha,
                coluna
            )

            if isinstance(
                celula,
                MergedCell
            ):
                continue

            celula.value = None


