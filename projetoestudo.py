def classificar_grafico_13(
    categorias
):

    texto = normalizar_13(
        " ".join(categorias)
    )

    if (
        "FEMININO" in texto
        or "MASCULINO" in texto
    ):
        return "GÊNERO"

    if (
        "FUNCIONARIO" in texto
        or "DEPENDENTE" in texto
        or "TITULAR" in texto
    ):
        return "TITULARIDADE"

    faixas = [
        "00 18",
        "19 23",
        "24 28",
        "29 33",
        "34 38",
        "39 43",
        "44 48",
        "49 53",
        "54 58",
        "59",
    ]

    quantidade_faixas = sum(
        1
        for faixa in faixas
        if faixa in texto
    )

    if quantidade_faixas >= 3:
        return "FAIXA ETÁRIA"

    if len(categorias) >= 3:
        return "DISTRIBUIÇÃO DE PLANOS"

    return "NÃO IDENTIFICADO"


