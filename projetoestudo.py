def limpar_texto_9(valor):
    if valor is None:
        return ""

    return " ".join(
        str(valor).replace("\n", " ").split()
    ).strip()


def normalizar_9(valor):
    texto = limpar_texto_9(valor)

    texto = unicodedata.normalize(
        "NFKD",
        texto
    )

    texto = "".join(
        caractere
        for caractere in texto
        if not unicodedata.combining(caractere)
    )

    texto = texto.upper()

    texto = re.sub(
        r"[^A-Z0-9%]+",
        " ",
        texto
    )

    return " ".join(texto.split())


TERMOS_NORMALIZADOS_9 = {
    normalizar_9(termo)
    for termo in TERMOS_RELEVANTES_9
}


def celula_e_formula_9(celula):
    return (
        isinstance(celula.value, str)
        and celula.value.startswith("=")
    )


def celula_tem_texto_relevante_9(valor):
    texto = normalizar_9(valor)

    if not texto:
        return False

    for termo in TERMOS_NORMALIZADOS_9:
        if termo and termo in texto:
            return True

    return False


def obter_intervalo_mesclado_9(ws, coordenada):
    for intervalo in ws.merged_cells.ranges:
        if coordenada in intervalo:
            return str(intervalo)

    return None


def analisar_vizinhanca_9(
    ws,
    linha,
    coluna,
    raio_linhas=2,
    raio_colunas=3
):
    vizinhanca = []

    linha_inicial = max(
        1,
        linha - raio_linhas
    )

    linha_final = min(
        ws.max_row,
        linha + raio_linhas
    )

    coluna_inicial = max(
        1,
        coluna - raio_colunas
    )

    coluna_final = min(
        ws.max_column,
        coluna + raio_colunas
    )

    for linha_atual in range(
        linha_inicial,
        linha_final + 1
    ):
        for coluna_atual in range(
            coluna_inicial,
            coluna_final + 1
        ):
            celula = ws.cell(
                linha_atual,
                coluna_atual
            )

            if isinstance(
                celula,
                MergedCell
            ):
                continue

            valor = limpar_texto_9(
                celula.value
            )

            if valor:
                vizinhanca.append({
                    "coordenada": celula.coordinate,
                    "valor": valor,
                    "formula": celula_e_formula_9(
                        celula
                    ),
                })

    return vizinhanca


def localizar_celulas_vazias_proximas_9(
    ws,
    linha,
    coluna,
    distancia=3
):
    vazias = []

    # Prioriza células à direita do marcador.
    for deslocamento in range(
        1,
        distancia + 1
    ):
        coluna_teste = coluna + deslocamento

        if coluna_teste > ws.max_column:
            break

        celula = ws.cell(
            linha,
            coluna_teste
        )

        if isinstance(
            celula,
            MergedCell
        ):
            continue

        if celula.value is None:
            vazias.append(
                celula.coordinate
            )

    # Depois verifica células logo abaixo.
    for deslocamento in range(
        1,
        distancia + 1
    ):
        linha_teste = linha + deslocamento

        if linha_teste > ws.max_row:
            break

        celula = ws.cell(
            linha_teste,
            coluna
        )

        if isinstance(
            celula,
            MergedCell
        ):
            continue

        if celula.value is None:
            vazias.append(
                celula.coordinate
            )

    return vazias


def contar_celulas_preenchidas_9(ws):
    quantidade = 0

    for linha in ws.iter_rows():
        for celula in linha:
            if isinstance(
                celula,
                MergedCell
            ):
                continue

            if limpar_texto_9(
                celula.value
            ):
                quantidade += 1

    return quantidade


def contar_formulas_9(ws):
    quantidade = 0

