def localizar_cabecalho_base_7(ws):
    """
    Procura a linha com maior quantidade de cabeçalhos úteis.
    """

    aliases = {
        "nome": {
            "NOME",
            "NOME BENEFICIARIO",
            "BENEFICIARIO",
            "VIDA",
        },

        "sexo": {
            "SEXO",
            "GENERO",
        },

        "vinculo": {
            "ELEGIBILIDADE",
            "VINCULO",
            "TIPO",
            "TITULAR DEPENDENTE",
        },

        "faixa": {
            "FAIXA ETARIA",
            "FAIXA",
        },

        "plano": {
            "PLANO",
            "PLANO 2",
            "PLANO2",
            "PRODUTO",
            "PRODUTO ATUAL",
            "PLANO ATUAL",
        },

        "valor": {
            "VALOR",
            "VALOR ATUAL",
            "MENSALIDADE",
            "PRECO",
        },

        "idade": {
            "IDADE",
        },
    }

    melhor_linha = None
    melhor_score = 0
    melhor_mapa = {}

    limite_linhas = min(
        ws.max_row,
        50
    )

    for linha in range(
        1,
        limite_linhas + 1
    ):
        mapa = {}

        for coluna in range(
            1,
            ws.max_column + 1
        ):
            texto = normalizar_7(
                ws.cell(
                    linha,
                    coluna
                ).value
            )

            if not texto:
                continue

            for campo, nomes in aliases.items():

                if texto in nomes:
                    # Quando existem cabeçalhos repetidos,
                    # preserva o último Plano e a primeira
                    # ocorrência dos demais campos.
                    if campo == "plano":
                        mapa[campo] = coluna

                    elif campo not in mapa:
                        mapa[campo] = coluna

        campos_essenciais = {
            "nome",
            "plano",
        }

        score = len(mapa)

        if (
            campos_essenciais.issubset(
                mapa.keys()
            )
            and score > melhor_score
        ):
            melhor_linha = linha
            melhor_score = score
            melhor_mapa = mapa

    if melhor_linha is None:
        raise ValueError(
            "O cabeçalho da Base não foi localizado."
        )

    return (
        melhor_linha,
        melhor_mapa,
        melhor_score
    )


